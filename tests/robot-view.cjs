/* System 22 check in the open game: choosing the robot, its company, its
   talents and its trip.   node tests/robot-view.cjs */
const { launch, sleep } = require('../tools/cdp.cjs')
const OUT = process.env.OUT || '/tmp/boom-tests'
let fails = 0
const ok = (c, m) => { console.log((c ? '  ok   ' : '  FAIL ') + m); if (!c) fails++ }
;(async () => {
  const p = await launch({ w: 1280, h: 720, port: 9409 })
  await p.navigate('http://localhost:5181/?fakeads=1')
  const O = '__open'
  await p.waitFor(`!!document.querySelector('.choose-robot')`)
  // checked the moment the chooser appears: "Click to play" used to lie over it for its first 300 ms
  ok(await p.eval(`getComputedStyle(document.querySelector('.click-to-play')).display === 'none'`), '"Click to play" waits until the choice is made, from the first moment')
  await sleep(5000)
  ok(await p.eval(`!!document.querySelector('.choose-robot') && document.querySelectorAll('.robot-card').length === 3`), 'a new player is asked to choose one of three robots')
  await p.shot(OUT + '/rb1-choose.png')
  await p.eval(`document.querySelector('.robot-card[data-k="sonar"]').click()`); await sleep(200)
  await p.eval(`document.querySelector('.choose-robot input').value = 'Beep<b>!'`)
  await p.eval(`document.querySelector('.choose-robot .go').click(); document.querySelector('.comic .skip') && document.querySelector('.comic .skip').click(); document.querySelector('.daily .claim') && document.querySelector('.daily .claim').click()`); await sleep(600)
  ok(JSON.stringify(await p.eval(`${O}.robot()`)) === '{"kind":"sonar","name":"Beep!"}', 'Sonar, named Beep (the markup stripped from the name)')
  ok(await p.eval(`${O}.talk().said[0].includes("Hi, I'm Beep!")`), 'it says hello and how to dig')
  await p.tap(640, 360); await sleep(1500)
  const near = await p.eval(`(() => { const b = ${O}.buddy().pos, q = ${O}.noa.entities.getPosition(${O}.noa.playerEntity); return Math.hypot(b[0] - q[0], b[1] - q[1] - 1.7, b[2] - q[2]) })()`)
  ok(near < 2.5, `it floats close by (${near.toFixed(2)} from your head)`)
  await p.eval(`${O}.noa.camera.heading = 0.4; ${O}.noa.camera.pitch = 0.1`); await sleep(700)
  await p.shot(OUT + '/rb2-buddy.png')
  // Sonar feels gold: put some 3 blocks ahead, underground
  await p.eval(`(() => { ${O}.noa.entities.setPosition(${O}.noa.playerEntity, [30.5, 1, 0.5]); ${O}.noa.camera.heading = 0; ${O}.world.set(30, 0, 4, 10) })()`); await sleep(3500)
  const said = await p.eval(`${O}.talk().said.concat(${O}.talk().queue).join(' | ')`)   // said, or next in line
  ok(/I feel gold ahead, \d blocks away/.test(said), `Sonar: "${said.split(" | ").find(x => /feel/.test(x))}" (said: ${said}; waiting: ${await p.eval(`${O}.talk().queue.join(" | ")`)})`)
  // its trip to the Market: it flies off and comes back
  await p.eval(`(() => { const x = 30, z = 0; for (let y = 0; y > -20; y--) ${O}.world.set(x, y, z, 0)
    ${O}.noa.entities.setPosition(${O}.noa.playerEntity, [x + 0.5, -19, z + 0.5]); ${O}.bag.add('gold'); ${O}.battery.charge = 0.1; ${O}.noa.camera.pitch = 1.55 })()`); await sleep(1500)
  await p.tap(640, 360); await sleep(200)
  await p.holdUntil(`${O}.card.open`); await sleep(300)
  await p.eval(`document.querySelector('[data-act="pick"]').click()`); await sleep(200)
  await p.eval(`document.querySelector('[data-act="robot"][data-arg="gold"]').click()`)
  ok(await p.waitFor(`${O}.buddy().away && ${O}.buddy().pos[1] > ${O}.state().y + 3`, 8000), 'sent to sell the gold, it flies off up the shaft')
  await p.eval(`${O}.rescue.t += 120`)
  await p.waitFor(`!${O}.buddy().away`, 8000); await sleep(300)
  ok(await p.eval(`!${O}.buddy().away && ${O}.digger.coins === 12`), 'and comes back with 12 coins')
  ok((await p.eval(`${O}.talk().said.concat(${O}.talk().queue).join(' | ')`)).includes('Ka-ching'), 'saying so (now or next in line)')
  await p.eval(`document.querySelector('[data-act="close"]') && document.querySelector('[data-act="close"]').click()`)
  // kept: no second choice after a reload
  await p.eval(`${O}.persist()`); await p.reload(); await sleep(6500)
  ok(await p.eval(`!document.querySelector('.choose-robot') && ${O}.robot().name === 'Beep!' && !!${O}.buddy()`), 'after a reload Beep is back, no second choice')
  // R: the robot's panel (row 35)
  await p.eval(`${O}.noa.entities.setPosition(${O}.noa.playerEntity, [30.5, 1, 0.5]); ${O}.bag.add('copper', 2); 1`); await sleep(500)
  await p.tap(640, 360); await sleep(300)
  await p.hold('KeyR', 80); await sleep(500)
  ok(await p.eval(`!!document.querySelector('.building .robot-head') && /your robot friend/.test(document.querySelector('.building').textContent)`), 'R opens the robot\'s panel: who it is and what it does')
  ok(!(await p.eval('!!document.pointerLockElement')), 'with the mouse free to click')
  await p.shot(OUT + '/rb4-panel.png')
  await p.eval(`document.querySelector('[data-act="tip"]').click()`); await sleep(300)
  ok(/\S/.test(await p.eval(`(document.querySelector('.building .said') || {}).textContent || ''`)), 'Give me a tip: a tip shows, and the robot says it')
  const coins0 = await p.eval(`${O}.digger.coins`)
  await p.eval(`document.querySelector('[data-act="send"][data-arg="copper"]').click()`); await sleep(400)
  ok(await p.eval(`${O}.buddy().away && ${O}.bag.items.copper === 1 && /off selling Copper/.test(document.querySelector('.building').textContent)`), 'send it with a copper: off it goes, the panel says so')
  await p.eval(`${O}.rescue.t += 120; 1`)
  ok(await p.waitFor(`${O}.digger.coins === ${coins0} + 3`, 8000), 'and it comes back with the 3 coins')
  const at = await p.eval(`(() => { const r = document.querySelector('.building .close').getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2] })()`)
  await p.tap(at[0], at[1]); await sleep(400)
  ok(await p.eval(`!document.querySelector('.building') && !!document.pointerLockElement`), 'Close: back in the game')
  ok(p.errors.length === 0, 'console clean ' + JSON.stringify(p.errors.slice(0, 3)))
  await p.close()

  // Bolt and Bzz: their talents
  const q = await launch({ w: 1280, h: 720, port: 9410 })
  await q.navigate('http://localhost:5181/'); await sleep(6500)
  await q.eval(`document.querySelector('.robot-card[data-k="bolt"]').click()`); await sleep(100)
  await q.eval(`document.querySelector('.choose-robot .go').click(); document.querySelector('.comic .skip') && document.querySelector('.comic .skip').click(); document.querySelector('.daily .claim') && document.querySelector('.daily .claim').click()`); await sleep(400)
  ok((await q.eval(`${O}.bag.capacity`)) === 30, 'Bolt: the backpack holds 30 instead of 20')
  await q.close()
  console.log(fails ? `${fails} failed` : 'all ok'); process.exit(fails ? 1 : 0)
})()
